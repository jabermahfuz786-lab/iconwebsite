export type PortalKey = keyof typeof bn;

export function usePortalText() {
  const { lang } = useApp();
  const dict = lang === 'en' ? en : bn;
  return { lang, t: (k: PortalKey): string => dict[k] };
}

export function formatMoney(amount: number, currency: string): string {
  return `${currency} ${Number(amount).toLocaleString('en-US', { maximumFractionDigits: 2 })}`;
}
